result = [3, 0, 5, 3, 2] # Изначальный список

result.append(10) # Добавлен в конец 10

result[0] = 5 # Первый элемент изменен на 5, с помощью индекса
# Индексы в Python начинаются с 0, поэтому result[0] — первый элемент

result.pop() # Удаления последнего элемента в списке командой .pop()

count = 0 # Накопитель для цикла

for i in result: # Простой цикл для вывода суммы всех значений внутри цикла
    count += i   # Прибавляем к накопителю текущее значение
print(count)     # Вывод суммы всех значений

print(sorted(result)) # sorted создает новый список не трогая изначальный
print(result)         # проверка на изменения изначального списка
result_tuple = tuple(result) # tuple() создаёт новый неизменяемый кортеж из списка
print(result_tuple) # Вывод кортежа
print(result_tuple[0]) # Первый элемент кортежа
print(result_tuple[-1]) # Последний элемент кортежа
# result_tuple[0] = 1  # TypeError: кортеж неизменяемый, элемент присваиванием не заменить
# Пояснение изменения списка изначально [3, 0, 5, 3, 2] => [3, 0, 5, 3, 2, 10] (.append() добавили в конце списка 10) =>
# [5, 0, 5, 3, 2, 10] (Первый элемент списка изменен на 5 напрямую по индексу) => [5, 0, 5, 3, 2] (Убрали 10 в конце
# с помощью .pop()).

# Проверка на других данных
# Беру другой список и повторяю те же действия, чтобы убедиться, что код работает не только на одном наборе
test = [4, 3, 4, 5, 1, 2] # Другой исходный список (6 элементов)

test.append(5) # Добавили 5 в конец: [4, 3, 4, 5, 1, 2, 5]

test[0] = 6 # Заменили первый элемент по индексу 0: [6, 3, 4, 5, 1, 2, 5]

test.pop() # Удалили последний элемент (5): [6, 3, 4, 5, 1, 2]

count = 0 # Накопитель суммы снова обнуляем, иначе прибавится старый результат

for i in test: # Проходим по каждому элементу списка
    count += i # Прибавляем текущий элемент к сумме

print(count) # Ожидаю 21 (6 + 3 + 4 + 5 + 1 + 2)
print(sorted(test)) # Новая отсортированная копия: [1, 2, 3, 4, 5, 6]
print(test) # Исходный список не изменился: [6, 3, 4, 5, 1, 2]
test_tuple = tuple(test) # Преобразуем список в неизменяемый кортеж
print(test_tuple) # (6, 3, 4, 5, 1, 2)
print(test_tuple[0]) # Первый элемент: 6
print(test_tuple[-1]) # Последний элемент: 2
# Результат совпадает с ожидаемым, значит код работает и на других данных